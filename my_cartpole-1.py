# The workers all have independent environments to run on
# The workers only do inference and the central agent does gradient descent 
# (or optimization since we might be using different algorithms like Adam and RMSProp)
# The agents create a batch of data which is composed of (observation, action, reward) tuple (might have a few other things too)
# The agents pass the data to the central agent which then does gradient descent on it
# After doing gradient descent, the weights of the central agent are updated and the newly updated weights of the central agent
# are assigned to the worker.
# The local agent (or equivalently, the worker) does not personally update its own gradients
# they are only updated by setting them to be equal to the gradients of the central agent
# It does not make sense to update the local agents as well by doing updates since we are setting their weights to equal the weights of the central agent. And it does not make sense to update the global agent's weight to that of the local agent after the personal weight updates of the local agent since that would remove the benefit to be had by having other local agents since between the time tha a given local agent provides two successive sets of data some other local agent might have provided its data which would have caused the central agent to progress.
